#!/usr/bin/env python3
"""Builds docs/verification/e2e-dataplane.{json,md} from the last run (tools/e2e/results.json) and matrix_meta.json.

  matrix.py [--results tools/e2e/results.json]

matrix_meta.json: {"scenarios": {name: {"issues": [...], "notes": "...", "commits": [...], "fixed_now": bool,
                                          "issue_notes": "..."}},
                   "not_testable": [{"scenario": ..., "issues": [...], "evidence": "why", "needs": "real-world evidence needed"}],
                   "not_covered": [{"scenario": ..., "issues": [...], "evidence": "..."}]}
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))

ap = argparse.ArgumentParser()
ap.add_argument("--results", default=os.path.join(HERE, "results.json"))
args = ap.parse_args()
res = json.load(open(args.results))
meta = json.load(open(os.path.join(HERE, "matrix_meta.json")))
rerun = "tools/e2e/run.sh --only "

rows = []
for r in res:
    m = meta["scenarios"].get(r["scenario"], {})
    issues = [i for i in (m.get("issues") if "issues" in m else r["issues"]) if str(i).isdigit()]
    tags = [i for i in r["issues"] if not str(i).isdigit()]
    status = r["status"]
    if status == "PASS" and m.get("fixed_now"):
        status = "FIXED-NOW"
    notes = m.get("notes", "")
    if tags:
        notes = (notes + " " if notes else "") + "[area: %s]" % ", ".join(tags)
    rows.append(dict(scenario=r["scenario"], issues=[int(i) for i in issues], status=status,
                     evidence="%s (rerun: %s%s)" % (r["evidence"].replace("\n", " ")[:700], rerun, r["scenario"]),
                     commits=m.get("commits", []), notes=notes))
for key, st in (("not_testable", "NOT-TESTABLE"), ("not_covered", "NOT-COVERED")):
    for m in meta.get(key, []):
        rows.append(dict(scenario=m["scenario"], issues=m.get("issues", []), status=st, evidence=m["evidence"], commits=[],
                         notes=m.get("needs", "")))

out_dir = os.path.join(ROOT, "docs", "verification")
os.makedirs(out_dir, exist_ok=True)
json.dump(rows, open(os.path.join(out_dir, "e2e-dataplane.json"), "w"), indent=1, ensure_ascii=False)
counts = {}
for r in rows:
    counts[r["status"]] = counts.get(r["status"], 0) + 1
lines = ["# Data-plane end-to-end verification", "",
         "Generated by `tools/e2e/matrix.py` from `tools/e2e/run.sh`. Every PASS row is a scenario that started a real Zoraxy, "
         "created the configuration through the admin API (or UI where noted) and sent real traffic to the proxy listener.", "",
         "Totals: " + ", ".join("%s=%d" % kv for kv in sorted(counts.items())), "",
         "| Scenario | Issues | Status | Evidence | Commits | Notes |", "|---|---|---|---|---|---|"]
for r in rows:
    esc = lambda s: s.replace("|", "\\|").replace("\n", " ")
    lines.append("| %s | %s | %s | %s | %s | %s |" % (r["scenario"], ", ".join("#%d" % i for i in r["issues"]) or "-", r["status"], esc(r["evidence"]),
                                                      ", ".join(r["commits"]) or "-", esc(r["notes"]) or "-"))
open(os.path.join(out_dir, "e2e-dataplane.md"), "w").write("\n".join(lines) + "\n")
print("wrote %d rows: %s" % (len(rows), counts))
