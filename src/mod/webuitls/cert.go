// Package webuitls provides HTTPS support helpers for the Zoraxy admin panel (web UI):
// a long-lived self-signed certificate manager and a listener that serves TLS and
// redirects plain HTTP on the same port.
package webuitls

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

const (
	// CertFileName and KeyFileName are the file names inside the webui cert folder.
	CertFileName = "webui.crt"
	KeyFileName  = "webui.key"
	// markerFileName marks the pair as generated by Zoraxy (safe to regenerate).
	// A pair without the marker is treated as user supplied and never overwritten.
	markerFileName = ".autogenerated"

	CertValidity = 3650 * 24 * time.Hour
	RenewBefore  = 30 * 24 * time.Hour
)

// Mode of the web UI TLS.
const (
	ModeOff    = "off"
	ModeAuto   = "auto"
	ModeCustom = "custom"
)

// CertInfo describes the certificate that is loaded.
type CertInfo struct {
	Certificate  tls.Certificate
	Fingerprint  string // SHA-256, upper-case colon separated hex
	Generated    bool   // true if generated (or regenerated) during this call
	UserSupplied bool
	NotAfter     time.Time
}

// LocalIdentities returns the DNS names and IPs this machine can be reached by.
func LocalIdentities() ([]string, []net.IP) {
	names := map[string]bool{"localhost": true}
	if h, err := os.Hostname(); err == nil && h != "" {
		names[strings.ToLower(h)] = true
	}
	ips := map[string]net.IP{}
	add := func(ip net.IP) {
		if ip != nil {
			ips[ip.String()] = ip
		}
	}
	add(net.ParseIP("127.0.0.1"))
	add(net.ParseIP("::1"))
	if addrs, err := net.InterfaceAddrs(); err == nil {
		for _, a := range addrs {
			if ipn, ok := a.(*net.IPNet); ok {
				// Skip link-local IPv6 which is zone dependent and noisy
				if ipn.IP.IsLinkLocalUnicast() && ipn.IP.To4() == nil {
					continue
				}
				add(ipn.IP)
			}
		}
	}
	var nl []string
	for n := range names {
		nl = append(nl, n)
	}
	sort.Strings(nl)
	var il []net.IP
	for _, ip := range ips {
		il = append(il, ip)
	}
	sort.Slice(il, func(i, j int) bool { return il[i].String() < il[j].String() })
	return nl, il
}

// EnsureCert loads (or creates) the web UI certificate inside dir.
// If mode is ModeCustom, a user supplied pair must exist and is never modified.
// If mode is ModeAuto and a pair without the auto marker exists, it is used as is.
func EnsureCert(dir string, mode string) (*CertInfo, error) {
	if mode != ModeAuto && mode != ModeCustom {
		return nil, fmt.Errorf("invalid web UI TLS mode %q", mode)
	}
	if err := os.MkdirAll(dir, 0700); err != nil {
		return nil, err
	}
	crtPath := filepath.Join(dir, CertFileName)
	keyPath := filepath.Join(dir, KeyFileName)
	markerPath := filepath.Join(dir, markerFileName)

	_, crtErr := os.Stat(crtPath)
	_, keyErr := os.Stat(keyPath)
	_, markErr := os.Stat(markerPath)
	pairExists := crtErr == nil && keyErr == nil
	autogenerated := markErr == nil

	if mode == ModeCustom {
		if !pairExists {
			return nil, fmt.Errorf("webui_tls=custom requires %s and %s in %s", CertFileName, KeyFileName, dir)
		}
		info, err := loadPair(crtPath, keyPath)
		if err != nil {
			return nil, err
		}
		info.UserSupplied = true
		return info, nil
	}

	if pairExists && !autogenerated {
		// User supplied files take precedence, never overwrite
		info, err := loadPair(crtPath, keyPath)
		if err != nil {
			return nil, fmt.Errorf("user supplied web UI certificate is invalid: %w", err)
		}
		info.UserSupplied = true
		return info, nil
	}

	if pairExists {
		if info, err := loadPair(crtPath, keyPath); err == nil && certStillGood(info.Certificate.Leaf, time.Now()) {
			return info, nil
		}
	}
	// (Re)generate
	if err := generate(crtPath, keyPath, markerPath); err != nil {
		return nil, err
	}
	info, err := loadPair(crtPath, keyPath)
	if err != nil {
		return nil, err
	}
	info.Generated = true
	return info, nil
}

func certStillGood(leaf *x509.Certificate, now time.Time) bool {
	if leaf == nil || now.Before(leaf.NotBefore) || now.Add(RenewBefore).After(leaf.NotAfter) {
		return false
	}
	names, ips := LocalIdentities()
	for _, n := range names {
		if err := leaf.VerifyHostname(n); err != nil {
			return false
		}
	}
	for _, ip := range ips {
		if err := leaf.VerifyHostname(ip.String()); err != nil {
			return false
		}
	}
	return true
}

func loadPair(crtPath, keyPath string) (*CertInfo, error) {
	pair, err := tls.LoadX509KeyPair(crtPath, keyPath)
	if err != nil {
		return nil, err
	}
	if len(pair.Certificate) == 0 {
		return nil, errors.New("empty certificate chain")
	}
	leaf, err := x509.ParseCertificate(pair.Certificate[0])
	if err != nil {
		return nil, err
	}
	pair.Leaf = leaf
	return &CertInfo{Certificate: pair, Fingerprint: Fingerprint(leaf), NotAfter: leaf.NotAfter}, nil
}

// Fingerprint returns the SHA-256 fingerprint of a certificate as AA:BB:...
func Fingerprint(c *x509.Certificate) string {
	sum := sha256.Sum256(c.Raw)
	h := strings.ToUpper(hex.EncodeToString(sum[:]))
	parts := make([]string, 0, len(sum))
	for i := 0; i < len(h); i += 2 {
		parts = append(parts, h[i:i+2])
	}
	return strings.Join(parts, ":")
}

func generate(crtPath, keyPath, markerPath string) error {
	priv, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return err
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 127))
	if err != nil {
		return err
	}
	names, ips := LocalIdentities()
	now := time.Now()
	cn := "localhost"
	if h, err := os.Hostname(); err == nil && h != "" {
		cn = h
	}
	tpl := &x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: cn, Organization: []string{"Zoraxy Web UI (self-signed)"}},
		NotBefore:             now.Add(-1 * time.Hour),
		NotAfter:              now.Add(CertValidity),
		KeyUsage:              x509.KeyUsageDigitalSignature,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		DNSNames:              names,
		IPAddresses:           ips,
	}
	der, err := x509.CreateCertificate(rand.Reader, tpl, tpl, &priv.PublicKey, priv)
	if err != nil {
		return err
	}
	keyDer, err := x509.MarshalECPrivateKey(priv)
	if err != nil {
		return err
	}
	crtPem := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
	keyPem := pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: keyDer})
	if err := os.WriteFile(keyPath, keyPem, 0600); err != nil {
		return err
	}
	if err := os.Chmod(keyPath, 0600); err != nil {
		return err
	}
	if err := os.WriteFile(crtPath, crtPem, 0644); err != nil {
		return err
	}
	return os.WriteFile(markerPath, []byte("generated by Zoraxy; delete this file to take ownership of webui.crt/webui.key\n"), 0644)
}
