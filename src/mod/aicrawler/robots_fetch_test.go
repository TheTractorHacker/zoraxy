func TestGuardedClientRefusesInternalTargets(t *testing.T) {
	// an allow-listed name that resolves to an internal address (DNS rebinding / misconfiguration) is refused at dial time
	old := lookupIP
	defer func() { lookupIP = old }()
	lookupIP = func(ctx context.Context, host string) ([]netip.Addr, error) {
		return []netip.Addr{netip.MustParseAddr("93.184.216.34"), netip.MustParseAddr("10.0.0.5")}, nil // one bad address poisons the answer
	}
	f := &Fetcher{Sources: []Source{{"a", "https://lists.example/x.json"}}, MaxBytes: 1024}
	f.Client = newGuardedClient(2*time.Second, nil, nil)
	if _, err := f.Fetch(context.Background(), "https://lists.example/x.json"); err == nil || !strings.Contains(err.Error(), "refused") {
		t.Fatalf("mixed answer must be refused, got %v", err)
	}
	// a literal loopback address in the allow-list (it is not on the built-in list, but the guard is independent of it)
	srv := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { w.Write([]byte(`["192.0.2.0/24"]`)) }))
	defer srv.Close()
	g := &Fetcher{Sources: []Source{{"a", srv.URL + "/x.json"}}, MaxBytes: 1024}
	g.Client = newGuardedClient(2*time.Second, nil, nil)
	if _, err := g.Fetch(context.Background(), srv.URL+"/x.json"); err == nil || !strings.Contains(err.Error(), "refused") {
		t.Fatalf("loopback target must be refused, got %v", err)
	}
}

func testFetcher(srv *httptest.Server, path string, max int64) *Fetcher {
	f := &Fetcher{Sources: []Source{{"openai-gptbot", srv.URL + path}}, MaxBytes: max, allowPrivate: true}
	f.Client = srv.Client() // trusts the test certificate; the dial guard itself is covered above
	f.Client.Timeout = 2 * time.Second
	f.Client.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	return f
}

func TestRefreshFixtures(t *testing.T) {
	mux := http.NewServeMux()
	mux.HandleFunc("/ok.json", func(w http.ResponseWriter, r *http.Request) {
		w.Write([]byte(`{"prefixes":[{"ipv4Prefix":"192.0.2.0/24"},{"ipv6Prefix":"2001:db8::/32"}]}`))
	})
	mux.HandleFunc("/redirect.json", func(w http.ResponseWriter, r *http.Request) { http.Redirect(w, r, "http://169.254.169.254/", 302) })
	mux.HandleFunc("/big.json", func(w http.ResponseWriter, r *http.Request) { w.Write([]byte(`["` + strings.Repeat("1", 5000) + `"]`)) })
	mux.HandleFunc("/err.json", func(w http.ResponseWriter, r *http.Request) { http.Error(w, "no", 500) })
	mux.HandleFunc("/garbage.json", func(w http.ResponseWriter, r *http.Request) { w.Write([]byte(`<html>hi</html>`)) })
	mux.HandleFunc("/slow.json", func(w http.ResponseWriter, r *http.Request) {
		time.Sleep(3 * time.Second)
		w.Write([]byte(`["192.0.2.1"]`))
	})
	srv := httptest.NewTLSServer(mux)
	defer srv.Close()

	store := NewRangeStore(filepath.Join(t.TempDir(), "r.json"))
	res := store.Refresh(context.Background(), testFetcher(srv, "/ok.json", 4096), nil)
	if len(res) != 1 || !res[0].OK || res[0].Count != 2 {
		t.Fatalf("%+v", res)
	}
	if in, _ := store.Contains([]string{"openai-gptbot"}, netip.MustParseAddr("192.0.2.77")); !in {
		t.Fatal("refreshed range not loaded")
	}
	// every failure keeps the data that was already there
	for _, p := range []string{"/redirect.json", "/big.json", "/err.json", "/garbage.json", "/slow.json"} {
		res := store.Refresh(context.Background(), testFetcher(srv, p, 1024), nil)
		if len(res) != 1 || res[0].OK || res[0].Error == "" {
			t.Errorf("%s: expected an error, got %+v", p, res)
		}
		if in, _ := store.Contains([]string{"openai-gptbot"}, netip.MustParseAddr("192.0.2.77")); !in {
			t.Errorf("%s: a failed refresh dropped the old data", p)
		}
	}
	// a URL outside the allow-list is never contacted
	hit := false
	other := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { hit = true }))
	defer other.Close()
	f := testFetcher(srv, "/ok.json", 4096)
	if _, err := f.Fetch(context.Background(), other.URL+"/x.json"); err == nil || hit {
		t.Fatal("a non-allow-listed URL was contacted")
	}
	// only the requested sources
	f2 := &Fetcher{Sources: []Source{{"a", "https://a.example/x"}, {"b", "https://b.example/x"}}}
	if got := store.Refresh(context.Background(), f2, []string{"zzz"}); len(got) != 0 {
		t.Fatalf("unknown ids select nothing: %+v", got)
	}
}

func TestNothingFetchedAtStartup(t *testing.T) {
	// New / Load never touch the network: no Fetcher exists unless the glue builds one for a refresh request
	e := New(filepath.Join(t.TempDir(), "a.json"), filepath.Join(t.TempDir(), "r.json"))
	if err := e.Load(); err != nil {
		t.Fatal(err)
	}
	for _, s := range e.Ranges.Status() {
		if s.Loaded {
			t.Fatal("a fresh engine must hold no ranges")
		}
	}
}
