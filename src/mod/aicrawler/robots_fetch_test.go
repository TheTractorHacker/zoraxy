func TestFetcherAllowList(t *testing.T) {
	f := &Fetcher{Sources: []Source{{"a", "https://example.com/list.json"}}}
	for _, u := range []string{
		"http://example.com/list.json",   // plain http
		"https://example.com/other.json", // other path
		"https://evil.example/list.json", // other host
		"https://example.com.evil.example/list.json",
		"https://user:pw@example.com/list.json", // userinfo
		"https://example.com/list.json?x=1",     // query
		"https://example.com:8443/list.json",    // other port
		"https://127.0.0.1/list.json", "https://169.254.169.254/latest/meta-data", "file:///etc/passwd", "ftp://example.com/list.json", "", "//example.com/list.json",
	} {
		if f.allowed(u) {
			t.Errorf("%q allowed", u)
		}
		if _, err := f.Fetch(context.Background(), u); err == nil {
			t.Errorf("%q fetched", u)
		}
	}
	if !f.allowed("https://example.com/list.json") || !f.allowed("https://EXAMPLE.com/list.json") {
		t.Error("the exact URL must be allowed")
	}
	// the real allow-list holds only https URLs without a query
	for _, s := range Sources() {
		if !NewFetcher().allowed(s.URL) {
			t.Errorf("built-in source %s not allowed by its own guard", s.ID)
		}
	}
}

