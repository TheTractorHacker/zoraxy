// ---- robots.txt / llms.txt generation ----

func TestRobotsGeneration(t *testing.T) {
	c := enabledCfg(func(c *Config) {
		c.Global.Groups = map[string]string{GroupTraining: ActBlock, GroupAgent: ActAllow, GroupSearch: ActRateLimit}
		c.Global.Crawlers = map[string]string{"ccbot": ActLog, "claudebot": ActChallenge}
	})
	c = c.normalise()
	rules := c.RobotsRules("s")
	if !strings.Contains(rules, "User-agent: GPTBot\n") || !strings.Contains(rules, "Disallow: /\n") {
		t.Fatalf("training crawlers must be disallowed:\n%s", rules)
	}
	if !strings.Contains(rules, "User-agent: ClaudeBot\n") {
		t.Error("a challenged crawler is disallowed in robots.txt too")
	}
	if !strings.Contains(rules, "User-agent: Google-Extended\n") || !strings.Contains(rules, "User-agent: Applebot-Extended\n") {
		t.Error("robots-only tokens follow the group policy")
	}
	if strings.Contains(rules, "User-agent: CCBot\n") {
		t.Error("log-only has no robots.txt equivalent")
	}
	if strings.Contains(rules, "PerplexityBot") {
		t.Error("rate limit has no robots.txt equivalent")
	}
	if !strings.Contains(rules, "User-agent: ChatGPT-User\n") || !strings.Contains(rules, "Allow: /\n") {
		t.Error("allowed crawlers get an explicit Allow group")
	}
	// every group ends with a blank line, no stray tokens, deterministic
	if rules != c.RobotsRules("s") {
		t.Error("generation must be deterministic")
	}
	file := c.RobotsFile("s")
	if !strings.HasPrefix(file, "# Generated by Zoraxy") || !strings.Contains(file, "advisory") || !strings.HasSuffix(file, "User-agent: *\nDisallow:\n") {
		t.Fatalf("serve text:\n%s", file)
	}
	app := c.RobotsAppend("s")
	if !strings.HasPrefix(app, "\n# Generated") {
		t.Fatalf("append text must start on its own line:\n%q", app)
	}
	// nothing to say -> nothing to append
	empty := enabledCfg(nil)
	if empty.RobotsAppend("s") != "" || empty.RobotsRules("s") != "" {
		t.Error("a policy without actions must not generate rules")
	}
	// per site override changes the generated text
	c.Sites = map[string]*SiteCfg{"open": {Mode: SiteCustom, Custom: SiteSettings{Crawlers: map[string]string{"gptbot": ActAllow}}}}
	open := c.RobotsRules("open")
	cut := strings.LastIndex(open, "Disallow: /\n\n")
	if strings.Contains(open[:cut], "User-agent: GPTBot") || !strings.Contains(open[cut:], "User-agent: GPTBot") {
		t.Errorf("the site override of GPTBot must move it to the allow group:\n%s", open)
	}
	// no user text ever lands in robots.txt: only registry tokens
	for _, line := range strings.Split(file, "\n") {
		if strings.HasPrefix(line, "User-agent: ") {
			tok := strings.TrimPrefix(line, "User-agent: ")
			found := tok == "*"
			for _, e := range Registry() {
				if e.Token == tok {
					found = true
				}
			}
			if !found {
				t.Errorf("unknown token %q in the generated file", tok)
			}
		}
	}
}

func TestFileModes(t *testing.T) {
	e := newEngine(t, enabledCfg(func(c *Config) {
		c.Global.Groups = map[string]string{GroupTraining: ActBlock}
		c.Robots.Mode = RobotsMerge
		c.Sites = map[string]*SiteCfg{
			"serve.example":     {Robots: RobotsCfg{Mode: RobotsServe}, LLMS: LLMSCfg{Mode: LLMSServe, Text: "# Title\n> text"}},
			"off.example":       {Robots: RobotsCfg{Mode: RobotsOff}},
			"fallback.example":  {LLMS: LLMSCfg{Mode: LLMSFallback, Text: "x\n"}},
			"siteoff.example":   {Mode: SiteOff, Robots: RobotsCfg{Mode: RobotsServe}},
			"emptytext.example": {LLMS: LLMSCfg{Mode: LLMSServe}},
		}
	}))
	if m := e.FileFor("any.example", "/robots.txt"); m.Mode != "merge" || !strings.Contains(m.Body, "GPTBot") {
		t.Fatalf("global default merge: %+v", m)
	}
	if m := e.FileFor("serve.example", "/robots.txt"); m.Mode != "serve" || !strings.HasSuffix(m.Body, "Disallow:\n") {
		t.Fatalf("serve: %+v", m)
	}
	if m := e.FileFor("off.example", "/robots.txt"); m.Mode != "off" {
		t.Fatalf("site off beats the default: %+v", m)
	}
	if m := e.FileFor("siteoff.example", "/robots.txt"); m.Mode != "off" {
		t.Fatalf("a site switched off serves nothing: %+v", m)
	}
	if m := e.FileFor("serve.example", "/llms.txt"); m.Mode != "serve" || m.Body != "# Title\n> text\n" {
		t.Fatalf("llms serve: %+v", m)
	}
	if m := e.FileFor("fallback.example", "/llms.txt"); m.Mode != "fallback" {
		t.Fatalf("llms fallback: %+v", m)
	}
	if m := e.FileFor("emptytext.example", "/llms.txt"); m.Mode != "off" {
		t.Fatalf("no text, nothing served: %+v", m)
	}
	if m := e.FileFor("any.example", "/llms.txt"); m.Mode != "off" {
		t.Fatalf("llms.txt is off unless the admin wrote one: %+v", m)
	}
	if m := e.FileFor("any.example", "/other.txt"); m.Mode != "off" {
		t.Fatal("only robots.txt and llms.txt")
	}
	// default: nothing is served
	if m := New("", "").FileFor("serve.example", "/robots.txt"); m.Mode != "off" {
		t.Fatal("default must serve nothing")
	}
}

