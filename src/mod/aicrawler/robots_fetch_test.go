func TestParseRangeJSON(t *testing.T) {
	good := map[string]int{
		`{"creationTime":"2025-01-01","prefixes":[{"ipv4Prefix":"192.0.2.0/28"},{"ipv6Prefix":"2001:db8::/48"}]}`: 2,
		`{"prefixes":[{"ip_prefix":"192.0.2.0/24"}]}`:                                                             1,
		`["192.0.2.0/24","198.51.100.1"]`:                                                                         2,
		`[{"cidr":"192.0.2.0/24"}]`:                                                                               1,
	}
	for js, n := range good {
		got, err := ParseRangeJSON([]byte(js))
		if err != nil || len(got) != n {
			t.Errorf("%s: %v %v", js, got, err)
		}
	}
	for _, js := range []string{``, `not json`, `{}`, `{"prefixes":[]}`, `{"prefixes":[{"ipv4Prefix":"nonsense"}]}`, `{"prefixes":[{"x":"1.2.3.0/24"}]}`, `42`, `"x"`, `{"prefixes":[{"ipv4Prefix":"1.2.3.4/99"}]}`} {
		if got, err := ParseRangeJSON([]byte(js)); err == nil {
			t.Errorf("%q accepted: %v", js, got)
		}
	}
	var many strings.Builder
	many.WriteString(`["10.0.0.1"`)
	for i := 0; i < maxPrefixesPerSource+1; i++ {
		many.WriteString(`,"10.0.0.1"`)
	}
	many.WriteString(`]`)
	if _, err := ParseRangeJSON([]byte(many.String())); err == nil {
		t.Error("an oversized list must be refused")
	}
}

func TestRangeStorePersistsAndDropsUnknownSources(t *testing.T) {
	p := filepath.Join(t.TempDir(), "r.json")
	s := NewRangeStore(p)
	if err := s.SetPrefixes("openai-gptbot", []string{"192.0.2.0/24"}, time.Unix(1700000000, 0)); err != nil {
		t.Fatal(err)
	}
	if st, _ := os.Stat(p); st == nil || st.Mode().Perm() != 0o600 {
		t.Fatal("cache file must be 0600")
	}
	s2 := NewRangeStore(p)
	if err := s2.Load(); err != nil {
		t.Fatal(err)
	}
	if in, had := s2.Contains([]string{"openai-gptbot"}, netip.MustParseAddr("192.0.2.9")); !in || !had {
		t.Fatal("cache not reloaded")
	}
	if in, _ := s2.Contains([]string{"openai-gptbot"}, netip.MustParseAddr("192.0.3.9")); in {
		t.Fatal("outside address matched")
	}
	os.WriteFile(p, []byte(`{"sets":{"evil-source":{"fetched":1,"prefixes":["0.0.0.0/0"]}}}`), 0o600)
	s3 := NewRangeStore(p)
	s3.Load()
	if s3.Has("evil-source") {
		t.Fatal("a source outside the allow-list must be dropped on load")
	}
	if err := s.SetPrefixes("x", []string{"bad"}, time.Now()); err == nil {
		t.Fatal("invalid prefixes accepted")
	}
}

