package aicrawler

import (
	"strings"
)

/*
	robots.txt and llms.txt

	robots.txt is ADVISORY: a crawler may ignore it (some documented ones do). The generated file only states the
	wish; the block / challenge / rate limit actions of the policy are the enforcement. The two are independent:
	a site can have a policy without serving robots.txt and the other way round.

	Generated rules, per crawler with an effective action:
	  block, challenge   User-agent: <token>  / Disallow: /
	  allow              User-agent: <token>  / Allow: /     (a named group beats "User-agent: *", so this lets it in
	                                                          even where the rest of the file disallows everything)
	  ratelimit, log     nothing (no robots.txt equivalent)
	Robots-only tokens (Google-Extended, Applebot-Extended) follow allow / block the same way.
*/

const robotsHeader = "# Generated by Zoraxy (AI crawler policy). robots.txt is advisory: crawlers may ignore it.\n"

// RobotsRules renders the generated crawler section for a site (without any header when there is nothing to say)
func (c *Config) RobotsRules(site string) string {
	ef := c.effectiveFor(site)
	var disallow, allow []string
	for _, e := range registry {
		if e.Token == "" {
			continue
		}
		switch ef.actionFor(e) {
		case ActBlock, ActChallenge:
			disallow = append(disallow, e.Token)
		case ActAllow:
			allow = append(allow, e.Token)
		}
	}
	var b strings.Builder
	write := func(tokens []string, rule string) {
		if len(tokens) == 0 {
			return
		}
		for _, t := range tokens {
			b.WriteString("User-agent: " + t + "\n")
		}
		b.WriteString(rule + "\n\n")
	}
	write(disallow, "Disallow: /")
	write(allow, "Allow: /")
	return b.String()
}

// RobotsFile is the full text served in "serve" mode
func (c *Config) RobotsFile(site string) string {
	rules := c.RobotsRules(site)
	var b strings.Builder
	b.WriteString(robotsHeader)
	b.WriteString(rules)
	b.WriteString("User-agent: *\nDisallow:\n")
	return b.String()
}

// RobotsAppend is the text added to an upstream file in "merge" mode (starts with a blank line so it never joins the last line)
func (c *Config) RobotsAppend(site string) string {
	rules := c.RobotsRules(site)
	if rules == "" {
		return ""
	}
	return "\n" + robotsHeader + rules
}

// FileMode is what the proxy does with a request for /robots.txt or /llms.txt on a site
type FileMode struct {
	Mode string // off | serve | merge | fallback
	Body string // serve: the whole file; merge: the text to append; fallback: the whole file used when the upstream has none
}

// FileFor decides how /robots.txt (path "/robots.txt") or /llms.txt is handled for a site.
// While the policy is disabled, or the site is switched off, nothing is served.
func (e *Engine) FileFor(site, path string) FileMode {
	if e == nil {
		return FileMode{Mode: "off"}
	}
	c := e.cfg.Load()
	if !c.Enabled {
		return FileMode{Mode: "off"}
	}
	if s := c.Sites[site]; s != nil && s.Mode == SiteOff {
		return FileMode{Mode: "off"}
	}
	switch path {
	case "/robots.txt":
		switch c.robotsMode(site) {
		case RobotsServe:
			return FileMode{Mode: "serve", Body: c.RobotsFile(site)}
		case RobotsMerge:
			// the upstream file is kept and extended; without an upstream file the rules are served alone
			return FileMode{Mode: "merge", Body: c.RobotsAppend(site)}
		}
	case "/llms.txt":
		s := c.Sites[site]
		if s == nil || s.LLMS.Text == "" {
			return FileMode{Mode: "off"}
		}
		switch s.LLMS.Mode {
		case LLMSServe:
			return FileMode{Mode: "serve", Body: ensureNL(s.LLMS.Text)}
		case LLMSFallback:
			return FileMode{Mode: "fallback", Body: ensureNL(s.LLMS.Text)}
		}
	}
	return FileMode{Mode: "off"}
}

func ensureNL(s string) string {
	if strings.HasSuffix(s, "\n") {
		return s
	}
	return s + "\n"
}

